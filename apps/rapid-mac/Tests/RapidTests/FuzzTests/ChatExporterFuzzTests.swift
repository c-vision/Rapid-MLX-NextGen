    /// Hostile title collision stress: 100 sessions all titled the
    /// same, plus a couple titled with path traversal. The collision
    /// counter must produce 100 distinct entry stems and the archive
    /// must still pass unzip -t.
    ///
    /// Codex r1 MAJOR closure: assert the archive's listed entry
    /// names are unique (ZIP permits duplicate names, so an entry-
    /// count check alone would pass a broken collision counter that
    /// writes 100 identical paths). We use `unzip -l` to read the
    /// central directory's listed names and assert the .md / .json
    /// entry-name sets are 100-unique.
    @Test("bulkZip 100 same-title sessions land as distinct entries — collision counter survives stress")
    func bulkZipCollisionStress() throws {
        try requireUnzipBinary()
        var sessions: [ChatSession] = []
        let titles = [
            "New chat",
            "New chat",
            "New chat",
            "../../etc/passwd",
            "  ",
            "..",
            "...",
        ]
        for i in 0..<100 {
            let title = titles[i % titles.count]
            sessions.append(ChatSession(
                title: title,
                alias: "qwen3.5-4b",
                messages: [
                    ChatMessage(role: .user, content: "hi \(i)"),
                    ChatMessage(role: .assistant, content: "yo \(i)"),
                ]
            ))
        }
        let data = try ChatExporter.bulkZip(sessions)
        // Entry count = 1 manifest + 2 × 100 sessions
        let eocdBytes = Array(data.suffix(22))
        let entries = UInt16(eocdBytes[10]) | (UInt16(eocdBytes[11]) << 8)
        #expect(entries == 201)
        // Drop to tmp + unzip -t.
        let tmp = URL(fileURLWithPath: NSTemporaryDirectory())
            .appendingPathComponent("fuzz-bulkzip-collision-\(UUID().uuidString).zip")
        defer { try? FileManager.default.removeItem(at: tmp) }
        try FixtureIO.write(data, to: tmp)
        let proc = Process()
        proc.executableURL = URL(fileURLWithPath: "/usr/bin/unzip")
        proc.arguments = ["-tqq", tmp.path]
        try proc.run()
        proc.waitUntilExit()
        #expect(proc.terminationStatus == 0,
                "collision-stress archive failed /usr/bin/unzip -t (status=\(proc.terminationStatus))")

        // Codex r1 MAJOR: also assert the LISTED entry names are
        // unique. ZIP permits duplicate paths; the EOCD entry count
        // alone wouldn't catch a broken collision counter.
        let names = try listZipEntryNames(at: tmp)
        // 1 manifest + 100 .md + 100 .json = 201 distinct paths
        #expect(names.count == 201)
        #expect(Set(names).count == 201,
                "collision counter leaked duplicate names: \(names.count - Set(names).count) duplicates")
        let mdNames = names.filter { $0.hasSuffix(".md") }
        let jsonNames = names.filter { $0.hasSuffix(".json") && $0 != "manifest.json" }
        #expect(mdNames.count == 100)
        #expect(Set(mdNames).count == 100, "duplicate .md entry names")
        #expect(jsonNames.count == 100)
        #expect(Set(jsonNames).count == 100, "duplicate .json entry names")
    }

    /// Pull the listed entry names out of a ZIP via `unzip -l`. We
    /// parse the column-formatted output rather than re-implement a
    /// central-directory reader. Returns the file paths in archive
    /// order.
    private func listZipEntryNames(at url: URL) throws -> [String] {
        guard FileManager.default.fileExists(atPath: "/usr/bin/unzip") else {
            return []
        }
        let proc = Process()
        proc.executableURL = URL(fileURLWithPath: "/usr/bin/unzip")
        proc.arguments = ["-Z1", url.path]
        let stdout = Pipe()
        proc.standardOutput = stdout
        proc.standardError = Pipe()
        try proc.run()
        proc.waitUntilExit()
        let data = (try? stdout.fileHandleForReading.readToEnd()) ?? Data()
        let text = String(data: data, encoding: .utf8) ?? ""
        return text
            .split(separator: "\n", omittingEmptySubsequences: true)
            .map { String($0) }
    }

    /// ZIP-slip canary: extract a bulk archive whose sessions carry
    /// adversarial titles into a temp directory and assert no
    /// extracted path escapes the dir. The exporter sanitizes titles
    /// to a safe stem; we exercise that by actually running unzip and
    /// checking realpath.
    ///
    /// Codex r1 MAJOR closure: enumerating only ``extractDir`` after
    /// extraction is one-sided — an absolute-path entry (e.g.
    /// `/etc/passwd`) extracted by `unzip` could land OUTSIDE the dir
    /// and never be seen by the enumerator. Two extra gates:
    ///   1. Read every entry name from the central directory (`unzip
    ///      -Z1`) and reject any name that contains `..` segments or
    ///      starts with `/`.
    ///   2. Plant a canary file alongside ``extractDir`` and assert
    ///      its mtime didn't move (proving no entry resolved to that
    ///      sibling path during extraction).
    @Test("bulkZip + unzip -o: no extracted path escapes the destination directory (ZIP-slip)")
    func bulkZipNoSlip() throws {
        try requireUnzipBinary()
        let sessions: [ChatSession] = AdversarialTitles.path.map { evil in
            ChatSession(
                title: evil,
                alias: "qwen3.5-4b",
                messages: [
                    ChatMessage(role: .user, content: "a"),
                    ChatMessage(role: .assistant, content: "b"),
                ]
            )
        }
        let data = try ChatExporter.bulkZip(sessions)
        let dir = URL(fileURLWithPath: NSTemporaryDirectory())
            .appendingPathComponent("fuzz-slip-\(UUID().uuidString)")
        try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: dir) }
        let zipPath = dir.appendingPathComponent("archive.zip")
        try FixtureIO.write(data, to: zipPath)

        // Gate 1: central-directory name audit. The exporter's
        // ``sanitize`` strips `/` `\` plus path separators, then
        // drops leading `.` / `-`, so a valid archive's listed names
        // contain no `..` segments and no absolute-path prefix.
        let listedNames = try listZipEntryNames(at: zipPath)
        for name in listedNames {
            #expect(!name.hasPrefix("/"),
                    "ZIP-slip: absolute-path entry name in central directory: \(name)")
            // Reject any `..` path segment (would resolve above the
            // extract dir on a vulnerable extractor).
            let segments = name.split(separator: "/")
            for seg in segments {
                #expect(seg != "..",
                        "ZIP-slip: traversal segment '..' in entry name: \(name)")
            }
            // Reject backslash-flavoured Windows traversal too.
            #expect(!name.contains("\\.."),
                    "ZIP-slip: windows-style traversal in entry name: \(name)")
        }

        let extractDir = dir.appendingPathComponent("extract")
        try FileManager.default.createDirectory(at: extractDir, withIntermediateDirectories: true)

        // Gate 2: plant a canary file sibling to extractDir. If an
        // entry's path resolves to that sibling on extraction, the
        // file's contents would change.
        let canary = dir.appendingPathComponent("canary.txt")
        try "CANARY-ORIG".write(to: canary, atomically: true, encoding: .utf8)

        let proc = Process()
        proc.executableURL = URL(fileURLWithPath: "/usr/bin/unzip")
        proc.arguments = ["-o", zipPath.path, "-d", extractDir.path]
        proc.standardOutput = Pipe()
        proc.standardError = Pipe()
        try proc.run()
        proc.waitUntilExit()
        #expect(proc.terminationStatus == 0)

        // Canary still reads its original content.
        let canaryAfter = (try? String(contentsOf: canary, encoding: .utf8)) ?? ""
        #expect(canaryAfter == "CANARY-ORIG",
                "ZIP-slip: canary alongside extract dir was clobbered")

        // Enumerate every file under extractDir + check resolved
        // paths remain inside extractDir.
        let realRoot = (extractDir.path as NSString).resolvingSymlinksInPath
        let enumerator = FileManager.default.enumerator(atPath: extractDir.path)
        var anyExtracted = false
        while let p = enumerator?.nextObject() as? String {
            anyExtracted = true
            let full = extractDir.appendingPathComponent(p).path
            let resolved = (full as NSString).resolvingSymlinksInPath
            #expect(
                resolved.hasPrefix(realRoot),
                "ZIP-slip escape: \(resolved) escaped \(realRoot) (entry path \(p))"
            )
        }
        #expect(anyExtracted, "expected at least one extracted entry")
    }

