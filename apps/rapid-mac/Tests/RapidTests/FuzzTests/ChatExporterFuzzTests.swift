    // MARK: - atomicWrite

    /// Happy path: write, then read the bytes back via stdlib + check
    /// the file is mode 0600 + no temp file leaks.
    @Test("atomicWrite: success leaves a 0600 file with exact bytes + no .tmp leak")
    func atomicWriteSuccess() throws {
        let dir = URL(fileURLWithPath: NSTemporaryDirectory())
            .appendingPathComponent("fuzz-atomic-\(UUID().uuidString)")
        try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: dir) }
        let dest = dir.appendingPathComponent("out.bin")
        var rng = SplitMix64(seed: 0xA70_E101)
        let payload = Data((0..<8192).map { _ in UInt8(rng.next() & 0xFF) })
        try ChatExporter.atomicWrite(payload, to: dest)
        let read = try Data(contentsOf: dest)
        #expect(read == payload)
        // mode == 0600
        let attrs = try FileManager.default.attributesOfItem(atPath: dest.path)
        let perms = (attrs[.posixPermissions] as? NSNumber)?.uint16Value ?? 0
        #expect(perms == 0o600, "expected 0600, got 0o\(String(perms, radix: 8))")
        // No leftover .rapid-export-* in the parent dir
        let siblings = try FileManager.default.contentsOfDirectory(atPath: dir.path)
        let leaks = siblings.filter { $0.hasPrefix(".rapid-export-") }
        #expect(leaks.isEmpty, "leaked temp files: \(leaks)")
    }

    /// Symlink at the destination pointing OUTSIDE the parent dir.
    /// The atomic rename should land OUR bytes at the destination
    /// path and NOT follow the symlink to write into the target
    /// outside our sandbox.
    @Test("atomicWrite: pre-existing symlink at destination does NOT write outside")
    func atomicWriteSymlinkSafe() throws {
        let dir = URL(fileURLWithPath: NSTemporaryDirectory())
            .appendingPathComponent("fuzz-symlink-\(UUID().uuidString)")
        try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: dir) }
        // Target the attacker would like to clobber — a separate file
        // OUTSIDE the dir we're writing into.
        let attackerTarget = URL(fileURLWithPath: NSTemporaryDirectory())
            .appendingPathComponent("fuzz-symlink-target-\(UUID().uuidString).txt")
        try "ORIGINAL".write(to: attackerTarget, atomically: true, encoding: .utf8)
        defer { try? FileManager.default.removeItem(at: attackerTarget) }
        let dest = dir.appendingPathComponent("export.bin")
        // Plant a symlink at the destination.
        try FileManager.default.createSymbolicLink(at: dest, withDestinationURL: attackerTarget)
        let payload = Data("FRESH".utf8)
        try ChatExporter.atomicWrite(payload, to: dest)
        // After the write, the dest must contain our payload (the
        // symlink is replaced by our real file via rename), and the
        // attacker's target file must still contain "ORIGINAL".
        let read = try Data(contentsOf: dest)
        #expect(read == payload)
        let attackerStill = try Data(contentsOf: attackerTarget)
        #expect(attackerStill == Data("ORIGINAL".utf8),
                "symlink followed: attacker target was overwritten with \(String(data: attackerStill, encoding: .utf8) ?? "?")")
        // lstat: dest is a regular file post-call, not a symlink.
        var st = stat()
        let rc = lstat(dest.path, &st)
        #expect(rc == 0)
        let isLink = (st.st_mode & S_IFMT) == S_IFLNK
        #expect(!isLink, "destination is still a symlink post-write")
    }

    /// Failure path: write into a directory that doesn't exist. Open
    /// fails on the temp path; no temp files should leak.
    @Test("atomicWrite: failed open does NOT leak a .tmp file in the parent dir")
    func atomicWriteFailureNoLeak() throws {
