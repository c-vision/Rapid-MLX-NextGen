            // or leave a temp file behind.
            #expect(!FileManager.default.fileExists(atPath: dir.path),
                    "atomic write created the missing parent dir as a side effect")
        }
    }

    /// Concurrency: 32 threads racing to write the same destination.
    /// The brief asks: TOCTOU safety + one of them lands intact + no
    /// temp files leak. ``atomicWrite`` uses ``O_EXCL`` on a per-call
    /// UUID-suffixed tmp name, then ``rename`` to the final path. Two
    /// concurrent calls don't collide on the tmp side (UUIDs differ);
    /// the rename winner is whichever thread finishes last. The
    /// surviving file must be intact bytes from SOMEONE.
    ///
    /// Codex r1 MAJOR closure:
    ///   1. Collect each task's success / thrown error so the test
    ///      reports if a regression makes most writers fail.
    ///   2. Use a start barrier (DispatchGroup) so every writer is
    ///      ready before any actually calls ``atomicWrite`` — without
    ///      it the first-spawned task could finish before the last
    ///      one even starts (no real contention).
    ///   3. Use 64 KB payloads so the write phase is non-trivial; a
    ///      tiny 1 KB payload completes in ~10 μs and the race window
    ///      degenerates.
    @Test("atomicWrite: 32 concurrent writes to the same dest leave one intact file + no tmp leak", .timeLimit(.minutes(1)))
    func atomicWriteConcurrentRace() throws {
        let dir = URL(fileURLWithPath: NSTemporaryDirectory())
            .appendingPathComponent("fuzz-race-\(UUID().uuidString)")
        try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: dir) }
        let dest = dir.appendingPathComponent("out.bin")

        // 32 distinct payloads tagged with their writer index so we
        // can identify which winner survived. 64 KB so the write
        // phase actually takes measurable wall time and the race
        // window isn't degenerate (a 1 KB write finishes in ~10 μs,
        // smaller than thread-spawn latency, which lets the first
        // task complete before the last even starts).
        let payloads: [Data] = (0..<32).map { i in
            let stamp = "writer-\(i):"
            let reps = (64 * 1024) / stamp.utf8.count
            return Data(String(repeating: stamp, count: reps).utf8)
        }

        // Start barrier — every thread signals readiness, the
        // launcher waits for 32 signals, then opens the gate so all
        // 32 threads race the write-and-rename at the same time.
        let readyGroup = DispatchGroup()
        for _ in 0..<32 { readyGroup.enter() }
        let goSemaphore = DispatchSemaphore(value: 0)

        // NSLock-guarded outcomes — pthread-style mutation from each
        // worker thread is the simplest shape that's also visible
        // from the main thread after ``readyGroup.wait``.
        final class Outcomes: @unchecked Sendable {
            let lock = NSLock()
            var successes: Int = 0
            var failures: [Error] = []
        }
        let outcomes = Outcomes()

        // Codex r2 MAJOR closure: spawn dedicated NSThreads instead
        // of DispatchQueue.global() workers so a constrained CI runner
        // with a narrow global thread pool can't starve the
        // semaphore-blocked workers and deadlock until the 1-minute
        // test timeout.
        let workersDone = DispatchGroup()
        var threads: [Thread] = []
        for i in 0..<32 {
            let payload = payloads[i]
            workersDone.enter()
            let t = Thread {
                readyGroup.leave()
                goSemaphore.wait()
                do {
                    try ChatExporter.atomicWrite(payload, to: dest)
                    outcomes.lock.lock()
                    outcomes.successes += 1
                    outcomes.lock.unlock()
                } catch {
                    outcomes.lock.lock()
                    outcomes.failures.append(error)
                    outcomes.lock.unlock()
                }
                workersDone.leave()
            }
            t.name = "atomic-write-race-\(i)"
            threads.append(t)
        }
        // Start every thread first, then unblock the gate so all 32
        // race the write-and-rename simultaneously.
        for t in threads { t.start() }
        readyGroup.wait()
        for _ in 0..<32 { goSemaphore.signal() }
        workersDone.wait()

        outcomes.lock.lock()
        let successCount = outcomes.successes
        let failures = outcomes.failures
        outcomes.lock.unlock()

        // Every failed writer must surface a ``ChatExporterError`` —
        // never an undocumented type. A regression that started
        // throwing a different shape would surface here.
        for err in failures {
            guard let e = err as? ChatExporterError else {
                Issue.record("undocumented error from atomicWrite under race: \(err)")
                continue
            }
            if case .writeFailed = e {
                // expected category
            } else {
                Issue.record("unexpected ChatExporterError under race: \(e)")
            }
        }
        // ``rename`` on macOS replaces the existing target — every
        // writer's rename should succeed barring a transient EBUSY.
        // We pin > 50% succeed: a regression that serializes the
        // writers behind a mutex would still show as 32 success but
        // ordered, while a regression that broke ``O_EXCL`` and
        // turned everyone past the first into a hard failure would
        // surface here.
        #expect(successCount >= 16,
                "only \(successCount)/32 writers succeeded under race — atomicWrite may have regressed. Failures: \(failures.count)")

        // Some writer landed; the surviving bytes must equal exactly
        // one of the payloads.
        guard let final = try? Data(contentsOf: dest) else {
            Issue.record("no surviving file after race")
            return
        }
        #expect(payloads.contains(final),
                "surviving bytes don't match any writer's payload — torn write")
        // No temp leaks.
        let siblings = try FileManager.default.contentsOfDirectory(atPath: dir.path)
        let leaks = siblings.filter { $0.hasPrefix(".rapid-export-") }
        #expect(leaks.isEmpty, "leaked temp files after race: \(leaks)")
    }

    // MARK: - CRC32 vector sanity

    /// CRC32 of "" is 0x00000000; CRC32 of "123456789" is 0xCBF43926.
    /// Pin both — a future "optimisation" of the table-driven loop
    /// would re-trip these immediately.
    @Test("CRC32 reference vectors: empty + IEEE 802.3 standard")
    func crc32Vectors() {
        #expect(CRC32.checksum(Data()) == 0x00000000)
        #expect(CRC32.checksum(Data("123456789".utf8)) == 0xCBF43926)
        // 1 MiB of zero bytes: classic stress test.
        let zeros = Data(repeating: 0, count: 1 << 20)
        // Known: CRC32 of 1 MiB of zeros (IEEE) is 0xA738EA1C.
        #expect(CRC32.checksum(zeros) == 0xA738EA1C)
    }
