/// Adversarial input coverage for ``ChatExporter`` (issue #215).
///
/// Three encoders + a TOCTOU-guarded ``atomicWrite`` are the entire
/// public surface; this suite throws everything in the brief at each
/// of them (1000 random sessions; adversarial title/content/attachment
/// corpora; bulk-zip stress) and asserts every invariant the export
/// surface is supposed to hold.
///
/// Every iteration uses a SplitMix64-seeded RNG so a failure can be
/// replayed with the captured seed via a fixed-seed regression test.
// ``.serialized`` so the fuzz iterations (each drops a multi-KB..MB
// archive to a tmp file and shells out to /usr/bin/unzip) don't pile
// their file-descriptor / IO pressure on top of each other in the
// full parallel pool (issue #530). Fixture writes also retry on a
// transient EBADF via ``FixtureIO.write``.
@Suite("ChatExporter — fuzz", .timeLimit(.minutes(3)), .serialized)
struct ChatExporterFuzzTests {

    /// Helper: assert that `/usr/bin/unzip` is present on the runner.
    /// Codex r4 NIT: when missing, the per-test silent skips would
    /// quietly let the ZIP-interoperability gates degrade to no-ops.
    /// macOS 10.15+ ships `/usr/bin/unzip` from the base system, so
    /// a CI image without it is environment drift worth reporting.
    /// Failed `#require` here surfaces it loudly.
    private func requireUnzipBinary() throws {
        try #require(
            FileManager.default.fileExists(atPath: "/usr/bin/unzip"),
            "Required system binary /usr/bin/unzip not present — ZIP interop checks would silently no-op."
        )
    }

    // MARK: - Per-session encoder fuzz (1000 iterations)

    /// Pure-fn invariant: ``markdown(_:)`` never throws (it doesn't
    /// even have ``throws`` in its signature) and produces a String.
    /// We assert it returns SOMETHING for every input — even "" is
    /// fine — and that it never crashes the process. With 1000
    /// adversarial sessions covering every category in the brief.
    @Test("markdown(_:) survives 1000 adversarial sessions without crashing")
    func markdownNeverCrashes() {
        let baseSeed: UInt64 = 0xDEAD_BEEF_FACE_F00D
        let iterations = 1000
        for i in 0..<iterations {
            var rng = SplitMix64(seed: baseSeed &+ UInt64(i))
            let session = FuzzSessionFactory.makeSession(rng: &rng)
            let md = ChatExporter.markdown(session)
            // The renderer always emits at minimum the H1 + the stats
            // line; even an empty session produces > 0 bytes.
            #expect(!md.isEmpty,
                    "seed=\(baseSeed &+ UInt64(i)) iter=\(i) — markdown returned empty string")
            // Sanitizer pass: no control char survives (other than
            // tab + LF). The ChatTextSanitizer claim is bounded — a
            // single \u{0000} in the output would mean the sanitizer
            // missed a path.
            for scalar in md.unicodeScalars {
                let v = scalar.value
                let permitted = (v == 0x09 || v == 0x0A) || (v >= 0x20 && v != 0x7F)
                // Allow >= 0xA0 (non-control extended)
                let inExtended = v >= 0xA0
                #expect(
                    permitted || inExtended,
                    "seed=\(baseSeed &+ UInt64(i)) iter=\(i) — illegal control U+\(String(v, radix: 16)) leaked into markdown"
                )
            }
            // Sanitizer also strips bidi overrides — none should
            // appear in the output regardless of how the title /
            // content abused them.
            let bidiOverrides: Set<UInt32> = [
                0x061C, 0x200E, 0x200F,
                0x202A, 0x202B, 0x202C, 0x202D, 0x202E,
                0x2066, 0x2067, 0x2068, 0x2069,
            ]
            for s in md.unicodeScalars {
                #expect(
                    !bidiOverrides.contains(s.value),
                    "seed=\(baseSeed &+ UInt64(i)) iter=\(i) — bidi override U+\(String(s.value, radix: 16)) leaked"
                )
            }
        }
    }

    /// Round-trip invariant: ``json(_:)`` always succeeds + the
    /// decoded envelope's ``session`` equals the input session. The
    /// envelope's exact key set MUST stay locked.
    @Test("json(_:) round-trips 1000 adversarial sessions through ExportSessionV1")
    func jsonRoundTrip() throws {
        let baseSeed: UInt64 = 0xC0FF_EE00_DEAD_BEEF
        let iterations = 1000
        // Use the production decoder so Date fields with sub-second
        // precision (now generated by FuzzSessionFactory) round-trip
        // exactly — the #289 fix is contingent on encoder + decoder
        // staying in lockstep.
        let decoder = ChatExporter.jsonDecoder()
        let envelopeKeys: Set<String> = [
            "schemaVersion", "generator", "appVersion", "exportedAt", "session"
        ]
        for i in 0..<iterations {
            let seed = baseSeed &+ UInt64(i)
            var rng = SplitMix64(seed: seed)
            let session = FuzzSessionFactory.makeSession(rng: &rng)
            try captureFailure(seed: seed, iteration: i, label: "jsonRoundTrip") {
                let data = try ChatExporter.json(session)
                #expect(!data.isEmpty, "seed=\(seed) iter=\(i) — empty JSON")
                // Top-level keys are exactly the V1 contract — any
                // extra key here is a silent schema drift.
                guard let obj = try JSONSerialization.jsonObject(with: data) as? [String: Any] else {
                    Issue.record("seed=\(seed) iter=\(i) — JSON not a top-level object")
                    return
                }
                #expect(
                    Set(obj.keys) == envelopeKeys,
                    "seed=\(seed) iter=\(i) — envelope keys drifted: \(Set(obj.keys).sorted())"
                )
                // Round-trip the envelope. The decoded session MUST
                // equal the input — every adversarial field included.
                let decoded = try decoder.decode(ExportSessionV1.self, from: data)
                #expect(
                    decoded.session == session,
                    "seed=\(seed) iter=\(i) — round-tripped session != input"
                )
            }
        }
    }

    /// Guard the round-trip fix for machinefi/rapid-desktop#289. Pre-fix,
    /// ``JSONEncoder.dateEncodingStrategy = .iso8601`` wrote whole-second
    /// timestamps and ``JSONDecoder.dateDecodingStrategy = .iso8601``
    /// parsed the same shape — a sub-second ``Date()`` was silently
    /// truncated on round-trip. The fix swapped both halves to a custom
    /// strategy backed by ``ChatExporterDateFormat`` (ISO-8601 with
    /// ``.withFractionalSeconds``). This test pins both halves of the
    /// fixed behaviour:
    ///   1. A sub-second ``Date`` round-trips byte-for-byte through
    ///      ``ChatExporter.json`` + ``ChatExporter.jsonDecoder()``.
    ///   2. A whole-second ``Date`` continues to round-trip exactly.
    ///   3. A v0.7.16 archive (fractional-less timestamps) is still
    ///      readable by the new decoder — proves the backwards-compat
    ///      branch in ``ChatExporterDateFormat.decode``.
    ///
    /// If assertion (1) or (3) ever flips back to "not equal", the
    /// fractional-precision contract has regressed; revisit
    /// ``ChatExporter.jsonEncoder()`` / ``jsonDecoder()``.
    @Test("json round-trip: sub-second precision is preserved (#289 fixed)")
    func jsonSubsecondPrecisionLoss() throws {
        // Millisecond-precision sub-second value. ``ISO8601DateFormatter``
        // with ``.withFractionalSeconds`` writes 3 decimal digits, so an
        // input that's already ms-aligned round-trips bit-for-bit. Pre-
        // fix this was dropped to ``1_700_000_000.0`` (whole seconds).
        let withSubsecond = Date(timeIntervalSince1970: 1_700_000_000.123)
        let session = ChatSession(
            id: UUID(),
            title: "subsec",
            alias: "qwen3.5-4b",
            messages: [
                ChatMessage(
                    id: UUID(),
                    role: .user,
                    content: "hi",
                    createdAt: withSubsecond
                ),
            ],
            createdAt: withSubsecond,
            updatedAt: withSubsecond
        )
        let data = try ChatExporter.json(session)
        // Sanity: the encoded blob carries the fractional component
        // verbatim — a regression that drops back to whole seconds
        // would land here before the Equatable check.
        let raw = String(data: data, encoding: .utf8) ?? ""
        #expect(raw.contains(".123"),
                "encoded JSON missing fractional-seconds component — encoder regressed")
        let decoder = ChatExporter.jsonDecoder()
        let decoded = try decoder.decode(ExportSessionV1.self, from: data)
        // POST-FIX behaviour: sub-second precision survives round-trip.
        // If this fires, #289 has regressed — re-examine
        // ChatExporterDateFormat + jsonEncoder/jsonDecoder.
        #expect(decoded.session == session,
                "sub-second Date round-trip regressed — #289 fix has unraveled")
        // Microsecond-precision input rounds to millisecond on encode
        // (ISO-8601 wire format caps at 3 decimal digits). The decoded
        // value MUST land within 1 ms of the original so the documented
        // precision contract is enforced.
        let withMicrosecond = Date(timeIntervalSince1970: 1_700_000_000.123456)
        let microSession = ChatSession(
            id: UUID(),
            title: "micro",
            alias: "qwen3.5-4b",
            messages: [ChatMessage(role: .user, content: "hi", createdAt: withMicrosecond)],
            createdAt: withMicrosecond,
            updatedAt: withMicrosecond
        )
        let microData = try ChatExporter.json(microSession)
        let microDecoded = try decoder.decode(ExportSessionV1.self, from: microData)
        let delta = abs(microDecoded.session.createdAt.timeIntervalSince(withMicrosecond))
        #expect(delta < 0.001,
                "microsecond input drifted by \(delta)s on round-trip — should be < 1 ms")
        // Whole-second control: an integer-second Date round-trips
        // exactly.
        let wholeSecond = Date(timeIntervalSince1970: 1_700_000_000)
        let session2 = ChatSession(
            id: UUID(),
            title: "whole",
            alias: "qwen3.5-4b",
            messages: [ChatMessage(role: .user, content: "hi", createdAt: wholeSecond)],
            createdAt: wholeSecond,
            updatedAt: wholeSecond
        )
        let data2 = try ChatExporter.json(session2)
        let decoded2 = try decoder.decode(ExportSessionV1.self, from: data2)
        #expect(decoded2.session == session2)

        // Backwards-compat gate: compose a v0.7.16-shaped archive
        // (fractional-less ISO-8601 timestamps) by hand and confirm
        // the new decoder still reads it. This is the "future re-
        // import flow loads an old archive" contract.
        let legacyEnvelope = """
        {
          "appVersion" : "0.7.16",
          "exportedAt" : "2026-06-10T12:00:00Z",
          "generator" : "Rapid Desktop",
          "schemaVersion" : 1,
          "session" : {
            "alias" : "qwen3.5-4b",
            "createdAt" : "2026-06-10T12:00:00Z",
            "id" : "11111111-1111-1111-1111-111111111111",
            "isPinned" : false,
            "messages" : [
              {
                "content" : "hi",
                "createdAt" : "2026-06-10T12:00:00Z",
                "id" : "22222222-2222-2222-2222-222222222222",
                "reasoning" : "",
                "role" : "user",
                "status" : "complete"
              }
            ],
            "title" : "legacy",
            "updatedAt" : "2026-06-10T12:00:00Z"
          }
        }
        """
        let legacyData = Data(legacyEnvelope.utf8)
        let legacyDecoded = try decoder.decode(ExportSessionV1.self, from: legacyData)
        #expect(legacyDecoded.session.title == "legacy",
                "backwards-compat decoder rejected a v0.7.16-shaped archive")
        #expect(legacyDecoded.appVersion == "0.7.16")
    }

    // MARK: - Bulk ZIP

    /// Bulk-zip 25 archives × 20 random sessions (= 500 distinct
    /// adversarial sessions), then assert per archive:
    ///   * Output is non-empty + carries the EOCD magic.
    ///   * Entry count == 1 (manifest) + 2 × sessions.
    ///   * /usr/bin/unzip -t accepts every archive (no CRC errors).
    /// Smaller archives + more of them exercises the collision
    /// counter against repeated titles + the per-archive offset/CRC
    /// arithmetic in less wall time than 1000 × 1 single-session runs.
    @Test("bulkZip(_:) produces unzip-clean archives across adversarial corpora", .timeLimit(.minutes(3)))
    func bulkZipUnzipClean() throws {
        try requireUnzipBinary()
        // 25 archives × 20 sessions each — covers the same input
        // variety in less wall time than 1000 × 1, and exercises the
        // collision counter against repeated titles.
        let baseSeed: UInt64 = 0xBAD0_FACE_F00D_BEEF
        let archiveCount = 25
        let sessionsPerArchive = 20

        for a in 0..<archiveCount {
            let seed = baseSeed &+ UInt64(a)
            var rng = SplitMix64(seed: seed)
            var sessions: [ChatSession] = []
            for _ in 0..<sessionsPerArchive {
                sessions.append(
                    FuzzSessionFactory.makeSession(
                        rng: &rng,
                        maxMessages: 12,
                        maxContentBytes: 2048,
                        bulkSafe: true
                    )
                )
            }
            try captureFailure(seed: seed, iteration: a, label: "bulkZipUnzipClean") {
                let data = try ChatExporter.bulkZip(sessions)
                // PKZIP local-header magic at offset 0
                let head = Array(data.prefix(4))
                #expect(head == [0x50, 0x4b, 0x03, 0x04],
                        "seed=\(seed) iter=\(a) — missing local-header magic")
                // EOCD signature in last 22 bytes
                let eocdHead = Array(data.suffix(22).prefix(4))
                #expect(eocdHead == [0x50, 0x4b, 0x05, 0x06],
                        "seed=\(seed) iter=\(a) — missing EOCD signature")
                // entry count = manifest + 2 × sessions
                let eocdBytes = Array(data.suffix(22))
                let entries = UInt16(eocdBytes[10]) | (UInt16(eocdBytes[11]) << 8)
                #expect(
                    Int(entries) == 1 + 2 * sessionsPerArchive,
                    "seed=\(seed) iter=\(a) — entry count drift: \(entries) vs expected \(1 + 2 * sessionsPerArchive)"
                )

                // Drop to a tmp file + run /usr/bin/unzip -t against
                // it. The top-of-test ``requireUnzipBinary`` already
                // guarantees the binary is present.
                let tmp = URL(fileURLWithPath: NSTemporaryDirectory())
                    .appendingPathComponent("fuzz-bulkzip-\(seed)-\(a).zip")
                defer { try? FileManager.default.removeItem(at: tmp) }
                try FixtureIO.write(data, to: tmp)
                let proc = Process()
                proc.executableURL = URL(fileURLWithPath: "/usr/bin/unzip")
                proc.arguments = ["-tqq", tmp.path]
                let stderrPipe = Pipe()
                proc.standardError = stderrPipe
                proc.standardOutput = Pipe()
                try proc.run()
                proc.waitUntilExit()
                if proc.terminationStatus != 0 {
                    let errData = (try? stderrPipe.fileHandleForReading.readToEnd()) ?? Data()
                    let stderrText = String(data: errData, encoding: .utf8) ?? ""
                    Issue.record(
                        "seed=\(seed) iter=\(a) — /usr/bin/unzip -t failed (status=\(proc.terminationStatus)): \(stderrText)"
                    )
                }
            }
        }
    }

